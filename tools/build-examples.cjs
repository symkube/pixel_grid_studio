const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = ['hupoling.png', 'lvdong.jpg', 'mingqiannailv.jpg', 'nailong.png', 'yuexinmao.png'];
const images = Object.fromEntries(files.map(name => {
  const mime = name.endsWith('.png') ? 'image/png' : 'image/jpeg';
  return ['pics/' + name, `data:${mime};base64,${fs.readFileSync(path.join(root, 'pics', name)).toString('base64')}`];
}));
// Data URLs keep bundled examples readable by canvas even when opened via file://.
fs.writeFileSync(path.join(root, 'pics', 'examples-data.js'), '// Generated by tools/build-examples.cjs\nwindow.PixelExamples = ' + JSON.stringify(images) + ';\n');
console.log(`Bundled ${files.length} local example images.`);
